"""Build workload-independent core counts and absolute precision peaks for the review draft."""
import csv
import hashlib
import json
from pathlib import Path

from hardware_cost import MODES, deploy, full_precision_profiles, load_profiles

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT/'data/inputs/deployment_capacity.json'
OUTPUT = ROOT/'data/evidence/deployment_capacity_20261117'
TABLE = ROOT/'tables/temp/deployment_capacity.tex'


def main():
    config = json.loads(CONFIG.read_text())
    profiles, source = load_profiles()
    profiles = full_precision_profiles(profiles)
    deployments = deploy(profiles, config['alpha'], config['beta'],
                         config['baseline_cores'], config['dp_per_core'])
    rows = []
    for profile, row in zip(profiles, deployments):
        count = int(row['installed_sms'])
        assert count == min(row['area_limited_sms'], row['power_limited_sms'])
        assert row['installed_area_mm2'] <= row['area_budget_mm2'] + 1e-9
        assert row['max_dp_power_w'] <= row['dp_power_budget_w'] + 1e-9
        if not count:
            raise ValueError('This comparison requires feasible deployments for all nine candidates')
        for mode in MODES:
            expected = float(2*profile['frequency_hz']*config['dp_per_core']*count
                             *profile['modes'][mode]['native_k']/profile['ii']/10**12)
            assert expected == row[mode+'_peak_tflops']
        rows.append(dict(ratio=row['ratio'], area_cores=int(row['area_limited_sms']),
            power_cores=int(row['power_limited_sms']), deployed_cores=count,
            area_budget_mm2=row['area_budget_mm2'], installed_area_mm2=row['installed_area_mm2'],
            dp_power_budget_w=row['dp_power_budget_w'], max_dp_power_w=row['max_dp_power_w'],
            peripheral_area_per_core_mm2=row['peripheral_area_per_sm_mm2'],
            core_area_mm2=row['sm_area_mm2'], frequency_hz=row['frequency_hz'], ii=row['ii_cycles'],
            **{p+'_tflops':row[m+'_peak_tflops'] for p, m in zip(('bf16', 'fp8', 'fp4'), MODES)}))
    OUTPUT.mkdir(parents=True, exist_ok=True)
    csv_file = OUTPUT/'deployment_capacity.csv'
    with csv_file.open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]), lineterminator='\n')
        writer.writeheader()
        writer.writerows(rows)
    lines = [r'% Generated by scripts/build_deployment_capacity.py; review draft only.',
        r'\begin{table}[t]', r'\centering',
        r'\caption{Deployable cores and chip peak throughput under matched budgets.}',
        r'\label{tab:deployment_capacity}',
        r'\begingroup\footnotesize\setlength{\tabcolsep}{3pt}',
        r'\begin{tabular}{@{}crrrrrr@{}}\toprule',
        r'Ratio & \multicolumn{3}{c}{Core count} & \multicolumn{3}{c}{Peak throughput (TFLOP/s)} \\',
        r'\cmidrule(lr){2-4}\cmidrule(l){5-7}',
        r' & $n_j^A$ & $n_j^P$ & $n_j$ & BF16 & FP8 & FP4 \\\midrule']
    for row in rows:
        lines.append(f"{row['ratio']} & {row['area_cores']} & {row['power_cores']} & {row['deployed_cores']}"
                     f" & {row['bf16_tflops']:.2f} & {row['fp8_tflops']:.2f} & {row['fp4_tflops']:.2f}"+r' \\')
    lines += [r'\bottomrule\end{tabular}', r'\par\vspace{2pt}\raggedright\scriptsize',
        f"$\\alpha={config['alpha']}$, $\\beta={config['beta']}$; "
        f"$N_0={config['baseline_cores']}$, $D={config['dp_per_core']}$.",
        r'$n_j^A$/$n_j^P$: area/power limits; $n_j$: joint deployment.',
        r'FP8/FP4 use MXFP8 E4M3/MXFP4 E2M1 costs. Mode peaks are mutually exclusive.',
        r'\endgroup', r'\end{table}']
    TABLE.write_text('\n'.join(lines)+'\n')
    def fingerprint(path):
        return dict(path=str(path.relative_to(ROOT)), sha256=hashlib.sha256(path.read_bytes()).hexdigest())
    inputs = [CONFIG, Path(__file__), ROOT/'scripts/hardware_cost.py',
              ROOT/'data/DP_area_power/dp11_area_power_fixed_20261116.csv',
              ROOT/'data/DP_area_power/dp11_area_power_fixed_20261116.sources.json']
    manifest = dict(status='analytical_uncalibrated', config=config, hardware_source=source,
        inputs=[fingerprint(p) for p in inputs], outputs=[fingerprint(csv_file), fingerprint(TABLE)],
        checks=dict(candidate_count=len(rows), area_and_power_limits=True, physical_count_is_common_to_modes=True,
                    direct_peak_formula_matches=True),
        assumptions=['Fixed per-core peripheral area, calibrated from the baseline DP-area fraction.',
                     'Budget covers the modeled AI-core pool area and DP-array power; global overhead is outside this budget.',
                     'Maximum among measured mode-average DP powers, not an instantaneous electrical worst case.',
                     'Ideal full-utilization peak from DP capacity and frequency; no workload or GEMM latency model.'])
    (OUTPUT/'manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')
    print(f'Wrote {len(rows)} deployments and three absolute peaks per deployment.')


if __name__ == '__main__':
    main()
