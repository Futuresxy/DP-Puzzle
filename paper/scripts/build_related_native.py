"""Reproduce the temporary native-process comparison, without technology scaling."""
import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_RECORD = ROOT/'data/evidence/related_native_20261116'
OUT = SOURCE_RECORD
TABLE = ROOT/'tables/temp/related_ppa_native.tex'
SOURCE = ROOT/'data/process_normalization/table_efficiencies.csv'
AREA_UPDATE = ROOT/'data/evidence/related_native_area_update_20261117/author_area.json'
POWER_UPDATE = ROOT/'data/evidence/related_native_power_update_20261117/author_power.json'


def main():
    global OUT, TABLE
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--official',action='store_true',help='Write the promoted official table and a separate evidence batch')
    args=parser.parse_args()
    if args.official:
        OUT=POWER_UPDATE.parent
        TABLE=ROOT/'tables/related_ppa_native.tex'
    with SOURCE.open() as f:
        rows = [dict(work=r['work'], node_nm=r['node_nm'], metric=r['metric'],
                     format=r['format'], config=r['config'], value=float(r['native']),
                     status='native', source='retained native column; see source records')
                for r in csv.DictReader(f) if r['work']!='tenfour' and (r['work']!='ours' or r['config'] in ('1:2:4','0:2:4'))]
    # Latest user-provided comparison image fixes the earlier transposed metric names.
    for metric, values in [('energy',{'FP8':1.63,'FP16':.82}),('area',{'FP8':1.06,'FP16':.53})]:
        for mode,value in values.items():
            rows.append(dict(work='minifloats',node_nm=12,metric=metric,format=mode,
                config='',value=value,status='reported_comparison',source='user attachment; primary Table 4 supports FP8 throughput/area and energy'))
    # Figure 7(a), full TransDot, 1000 ps: approx 6000 um^2 of cell area.
    # Do not multiply 12 nm local FPnew relative gains by the unrelated 22 nm SIMD efficiencies.
    for mode,gflops in [('FP16',4),('FP8',8),('FP4',16)]:
        rows.append(dict(work='transdot',node_nm=12,metric='area',format=mode,config='',
            value=(gflops/1000)/(6000/1e6),status='figure_read_estimate',source='TransDot Fig. 7(a) at 1 ns and Table II throughput'))
    area_update=json.loads(AREA_UPDATE.read_text())
    for row in rows:
        if row['work']=='ours' and row['config']==area_update['config'] and row['metric']=='area':
            row['value']=area_update['throughput_gflops'][row['format']]*1000/area_update['area_um2']
            row['status']='author_area_update'
            row['source']=str(AREA_UPDATE.relative_to(ROOT))
    power_update=json.loads(POWER_UPDATE.read_text())
    for row in rows:
        if row['work']=='ours' and row['config']==power_update['config'] and row['metric']=='energy':
            row['value']=area_update['throughput_gflops'][row['format']]/power_update['total_power_mw'][row['format']]
            row['status']='author_power_update'
            row['source']=str(POWER_UPDATE.relative_to(ROOT))
    assert all(r['value']>0 for r in rows)
    def eff(work,metric,config=''):
        selected=[r for r in rows if r['work']==work and r['metric']==metric and r['config']==config]
        if not selected:return '---'
        return r'\Eff{'+r'\\'.join(r['format']+' & '+
            (r'$\approx '+f"{r['value']:.2f}"+r'^{\dagger}$' if r['status']=='figure_read_estimate'
             else f"{r['value']:.2f}" if work=='minifloats' else f"{r['value']:.3f}") for r in selected)+'}'
    table=r'''% Generated by scripts/build_related_native.py; temporary manuscript only.
\begin{table*}[t]
\centering
\caption{已有单元与 DP-Puzzle 的原工艺实现条件及效率。}
\label{tab:related_dp}
\begingroup\footnotesize\setlength{\tabcolsep}{1.5pt}
\def\Eff#1{\begin{tabular}{@{}lr@{}}#1\end{tabular}}
\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}l*{7}{c}@{}}\toprule
Metric & MPICC~\cite{huangMPICCMultiplePrecisionInterCombined2025} & MXDOTP~\cite{islamoglu2025mxdotp} & FPnew~\cite{mach2021fpnew_temp} & MiniFloats~\cite{bertaccini2024minifloats_temp} & TransDot~\cite{transdot2026} & \multicolumn{2}{c}{DP-Puzzle} \\
\cmidrule(lr){7-8}
 & & & & & & $1:2:4$ & $0:2:4$ \\
\midrule
Structure & $n$-term MAC & MX DP & SIMD FMA & SIMD wDotp & FMA / DP & MX DP & MX DP \\
Technology (nm) & 28 & 12 & 22 & 12 & 12 & 12 & 12 \\
Voltage (V) & 0.9 & 0.8 & 0.8 & 0.8 & 0.8 & 0.7 & 0.7 \\
Frequency (GHz) & 1.43 & 1.09 & 0.923 & 1.26 & 1.0 & 1.0 & 1.0 \\
Area ($\mu$m$^2$) & 2295 & 3150 & 49\,000 & 19\,000 & $\approx 6000^\dagger$ & 16\,165.12 & AUTHOR_AREA_UM2 \\
Accumulation & FP12/INT8 & FP32 & Per format & FP16/FP32 & FP32 & FP32/INT32 & FP32 \\
\midrule
'''
    works=[('mpicc',''),('mxdotp',''),('fpnew',''),('minifloats',''),('transdot',''),('ours','1:2:4'),('ours','0:2:4')]
    for metric,title in [('energy',r'\shortstack[l]{Energy efficiency\\(TFLOP/s/W)}'),('area',r'\shortstack[l]{Area efficiency\\(TFLOP/s/mm$^2$)}')]:
        table+=title+' & '+' & '.join(eff(w,metric,c) for w,c in works)+r' \\'+'\n'
        if metric=='energy':table+='\\midrule\n'
    table+=r'''\bottomrule\end{tabular*}
\par\smallskip
\parbox{\textwidth}{\raggedright
均为原工艺数据，不做工艺归一化；支持范围见表~\ref{tab:related_features}。MiniFloats 取独立 wDotp FPU，非 cluster。
$\dagger$：TransDot 面积由原文图 7(a) 的 1\,ns 点估读，面效按表 II 吞吐计算；原文相对其 12\,nm FPnew 基线的平均 FP16/FP8 面效为 1.46$\times$/2.92$\times$，不与本表 22\,nm FPnew 值相乘。--- 表示无报告值或不适用。}
\endgroup
\end{table*}
'''
    table=table.replace('AUTHOR_AREA_UM2',f"{area_update['area_um2']:,.2f}".replace(',',r'\,'))
    if args.official:
        table=table.replace('temporary manuscript only','official manuscript')
        table=table.replace('已有单元与 DP-Puzzle 的原工艺实现条件及效率。',
                            'Implementation conditions and efficiency at the reported process nodes.')
        table=table.replace(
            r'均为原工艺数据，不做工艺归一化；支持范围见表~\ref{tab:related_features}。MiniFloats 取独立 wDotp FPU，非 cluster。',
            r'All values use the reported process nodes without technology normalization; supported formats are listed in Table~\ref{tab:related_features}. MiniFloats reports the standalone wDotp FPU, excluding the cluster.')
        table=table.replace(
            r'$\dagger$：TransDot 面积由原文图 7(a) 的 1\,ns 点估读，面效按表 II 吞吐计算；原文相对其 12\,nm FPnew 基线的平均 FP16/FP8 面效为 1.46$\times$/2.92$\times$，不与本表 22\,nm FPnew 值相乘。--- 表示无报告值或不适用。',
            r'$\dagger$: TransDot cell area is estimated from the 1\,ns point in its Fig. 7(a), with area efficiency calculated using the throughput in its Table II. Its mean FP16/FP8 area-efficiency gains of 1.46$\times$/2.92$\times$ are relative to its own 12\,nm FPnew baseline and are not applied to the 22\,nm FPnew results here. --- denotes unreported or inapplicable values.')
        table=table.replace('mach2021fpnew_temp','mach2021fpnew').replace('bertaccini2024minifloats_temp','bertaccini2024minifloats')
    TABLE.parent.mkdir(parents=True,exist_ok=True);TABLE.write_text(table)
    OUT.mkdir(parents=True,exist_ok=True)
    with (OUT/'efficiencies.csv').open('w') as f:
        writer=csv.DictWriter(f,fieldnames=list(rows[0]),lineterminator='\n');writer.writeheader();writer.writerows(rows)
    def fp(path):return {'path':str(path.relative_to(ROOT)),'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}
    (OUT/'manifest.json').write_text(json.dumps(dict(scope=('official Table IV' if args.official else 'temporary Tables I and IV')+'; no process conversion',
        inputs=[fp(SOURCE),fp(AREA_UPDATE),fp(POWER_UPDATE),fp(Path(__file__)),fp(SOURCE_RECORD/'sources.json'),fp(SOURCE_RECORD/'user_comparison.png')],outputs=[fp(TABLE),fp(OUT/'efficiencies.csv')],
        transdot=dict(cell_area_um2_estimate=6000,period_ps=1000,frequency_ghz=1,
            local_fpnew_relative_area_efficiency={'FP16':dict(mean=1.46,range=[1.28,1.52]),'FP8':dict(mean=2.92,range=[1.56,3.04])},
            method='Absolute area efficiencies use figure-estimated cell area; quoted means span timing sweep and are not multiplied into 22 nm SIMD data'),
        minifloats=dict(energy={'FP8':1.63,'FP16':.82},area={'FP8':1.06,'FP16':.53},
                       source='Latest user screenshot supersedes transposed prose values')),
        indent=2)+'\n')
    print('Wrote native-process Table IV and',len(rows),'efficiency entries.')


if __name__=='__main__':main()
