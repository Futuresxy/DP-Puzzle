ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT/'data/inputs/v41_core.json'
OUTPUT = ROOT/'data/evidence/v41_core_20261116'
PRECISIONS = ('BF16','FP8','FP4')


def family(kernel):
    if kernel.startswith('moe.routed.'):
        return 'routed'
    if kernel.startswith('moe.shared.'):
        return 'shared'
    if kernel in ('q_up','o_final'):
        return 'projections'
    if kernel in ('swa.qk','swa.pv','global.qk','global.pv'):
        return 'attention'
    if kernel == 'o_group':
        return 'output'
    return None


def map_work(ledger, scenario):
    work, routed = np.zeros(3), np.zeros(3)
    excluded, core_flops, index_flops = 0, 0, 0
    for row in ledger:
        key = family(row['kernel'])
        precision = scenario[key] if key else row['precision']
        if precision not in PRECISIONS:
            if key:
                raise ValueError('Core scenario has unsupported precision')
            excluded += row['flops']
            continue
        mode = PRECISIONS.index(precision)
        work[mode] += row['flops']
        if key == 'routed':
            routed[mode] += row['flops']
        if key:
            core_flops += row['flops']
        if row['kernel'] in ('index.full_qk','index.candidate_qk'):
            index_flops += row['flops']
    if not np.isclose(work.sum()+excluded,sum(r['flops'] for r in ledger),rtol=1e-13):
        raise AssertionError('Scenario must conserve total work')
    return work,routed,excluded,core_flops,index_flops


def evaluate(work, routed, capacity, power, utilization):
    eta = np.array([1.,utilization['q'],utilization['e']])
    if not np.all(np.isfinite(eta)) or np.any((eta<=0)|(eta>1)):
        raise ValueError('Utilization must be in (0,1]')
    service_work = work-routed+routed/eta
    time = service_work@(1/capacity).T/1e12
    energy = work@(power/capacity).T/1e12 if np.all(eta==1) else None
    return time,energy


def summarize(times, energies, weights):
    weights=np.asarray(weights,dtype=float)
    weights=weights/weights.sum()
    slowdown=times/times.min(axis=1,keepdims=True)
    regret=slowdown.max(axis=0)-1
    mean_time=weights@times
    mean_energy=weights@energies if energies is not None else None
    objectives=np.column_stack((regret,mean_time)) if mean_energy is None else np.column_stack((regret,mean_time,mean_energy))
    return dict(worst_regret=regret,mean_slowdown=weights@slowdown,mean_seconds=mean_time,
                mean_dp_energy_j=mean_energy,speedup_over_baseline=mean_time[0]/mean_time,
                minimax=np.isclose(regret,min(regret),rtol=1e-10,atol=1e-12),pareto=pareto_mask(objectives),
                worst_case=slowdown.argmax(axis=0))


def render(config,cases,evaluations,metrics,ratios):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch
    plt.rcParams.update({'font.family':'serif','font.serif':['Times New Roman','Liberation Serif','STIXGeneral'],
                         'font.size':9,'pdf.fonttype':42,'mathtext.fontset':'stix'})
    alpha,beta=config['report_alpha'],config['report_beta']
    chosen=[r for r in metrics if r['alpha']==alpha and r['beta']==beta
            and r['utilization']=='ideal' and r['distribution']=='balanced']
    reference=[r for r in evaluations if r['alpha']==alpha and r['beta']==beta and r['utilization']=='ideal']
    lines=[r'% Generated by scripts/v41_core.py.',r'\begin{tabular}{@{}lcrrr@{}}\toprule',
           r'Case & Ratio & $R_j$ (\%) & $\bar{s}_j-1$ (\%) & Speedup \\\midrule']
    for case in [s['id'] for s in config['scenarios']]+list(config['portfolios']):
        for r in chosen:
            if r['portfolio']==case and r['minimax']:
                lines.append(f"{case.replace('_', ' ')} & ${r['ratio']}$ & {100*r['worst_regret']:.2f} & "
                             f"{100*(r['mean_slowdown']-1):.2f} & {r['speedup_over_baseline']:.2f}"+r' \\')
    lines.append(r'\bottomrule\end{tabular}')
    table=ROOT/'tables/v41_core_choice.tex';table.write_text('\n'.join(lines)+'\n')
    colors=['#3c5488','#b88a20','#008b70','#8064a2','#c44e52','#7a6a43','#367fa0','#91614b','#d05c9b']
    markers=['o','s','^','D','v','P','X','<','>']
    precision_colors=['#6996c2','#e2ab55','#83b7a0']
    fig=plt.figure(figsize=(7.16,5.15))
    outer=fig.add_gridspec(2,3,left=.075,right=.99,bottom=.16,top=.91,hspace=.36,wspace=.21)
    handles=[]
    for i,scenario in enumerate(config['scenarios']):
        sid=scenario['id'];sub=outer[i//3,i%3].subgridspec(2,1,height_ratios=[1,2.1],hspace=.10)
        top=fig.add_subplot(sub[0]);bottom=fig.add_subplot(sub[1],sharex=top)
        points=[r for r in cases if r['scenario']==sid]
        x=[r['context'] for r in points]
        top.stackplot(x,*[[100*r['x_'+p] for r in points] for p in 'HQE'],colors=precision_colors,linewidth=0)
        top.set(ylim=(0,100),yticks=[0,100],title=f"({sid.lower()}) {scenario['label']}")
        top.tick_params(axis='x',which='both',bottom=False,labelbottom=False)
        top.tick_params(axis='y',labelsize=7,pad=1)
        if i%3==0:top.set_ylabel('FLOP %',fontsize=8)
        best=[r for r in chosen if r['portfolio']==sid and r['minimax']]
        for j,ratio in enumerate(ratios):
            ys=[r['slowdown'] for r in reference if r['scenario']==sid and r['ratio']==ratio]
            selected=any(r['ratio']==ratio for r in best)
            line,=bottom.plot(x,ys,color=colors[j],marker=markers[j],markersize=2.8,
                linewidth=1.6 if selected else .7,linestyle='-' if j<5 else '--',label=ratio)
            if i==0:handles.append(line)
        bottom.set_xscale('log',base=2)
        bottom.set_xticks([1024,16384,262144,1048576],['1K','16K','256K','1M'])
        ymax=max(r['slowdown'] for r in reference if r['scenario']==sid)
        bottom.set_ylim(.94,ymax+.18)
        bottom.tick_params(labelsize=8,pad=2)
        bottom.grid(axis='y',alpha=.15,linewidth=.5)
        bottom.text(.03,.97,'; '.join(f"{r['ratio']}: {100*r['worst_regret']:.2f}%" for r in best),
                    transform=bottom.transAxes,va='top',fontsize=8)
        if i%3==0:bottom.set_ylabel('Slowdown',fontsize=8)
        if i>=3:bottom.set_xlabel('Context (tokens)',fontsize=8)
    fig.legend([Patch(facecolor=c) for c in precision_colors],['H','Q','E'],loc='upper center',
               ncol=3,frameon=False,fontsize=9,bbox_to_anchor=(.5,1.0),handlelength=1)
    fig.legend(handles,ratios,loc='lower center',ncol=5,frameon=False,fontsize=8,handlelength=2)
    figure=ROOT/'figures/v41_core_scenarios.pdf'
    fig.savefig(figure,bbox_inches='tight',pad_inches=.03,metadata={'CreationDate':None,'ModDate':None})
    plt.close(fig)
    return [table,figure]


def main():
    config=json.loads(CONFIG.read_text())
    profiles,metadata=load_profiles();profiles=full_precision_profiles(profiles)
    ratios=[p['ratio'] for p in profiles]
    cases,work,routed=[],[],[]
    ledgers={context:v41.prefill_work(context,batch=config['batch']) for context in config['contexts']}
    for scenario in config['scenarios']:
        for context,ledger in ledgers.items():
            f,r,excluded,core,index=map_work(ledger,scenario)
            work.append(f);routed.append(r)
            cases.append(dict(scenario=scenario['id'],context=context,h_flops=f[0],q_flops=f[1],e_flops=f[2],
                x_H=f[0]/sum(f),x_Q=f[1]/sum(f),x_E=f[2]/sum(f),excluded_fp32_flops=excluded,
                migration_target_fraction=core/(sum(f)+excluded),core_plus_index_fraction=(core+index)/(sum(f)+excluded)))
    work,routed=np.array(work),np.array(routed)
    evaluations,metrics,deployments=[],[],[]
    for alpha,beta in itertools.product(config['alphas'],config['betas']):
        rows=deploy(profiles,alpha,beta,config['baseline_sms'],config['dp_per_sm']);deployments.extend(rows)
        capacity=np.array([[r[m+'_peak_tflops'] for m in MODES] for r in rows])
        power=np.array([[r[m+'_dp_power_w'] for m in MODES] for r in rows])
        if np.any(capacity<=0):raise ValueError('Feasible deployment required')
        for utilization in config['utilization_cases']:
            times,energies=evaluate(work,routed,capacity,power,utilization)
            for i,case in enumerate(cases):
                for j,ratio in enumerate(ratios):
                    evaluations.append(dict(alpha=alpha,beta=beta,utilization=utilization['id'],scenario=case['scenario'],
                        context=case['context'],ratio=ratio,seconds=times[i,j],dp_energy_j=energies[i,j] if energies is not None else None,
                        slowdown=times[i,j]/min(times[i])))
            portfolios={s['id']:[s['id']] for s in config['scenarios']} | config['portfolios']
            for portfolio,members in portfolios.items():
                indices=[i for i,c in enumerate(cases) if c['scenario'] in members]
                for distribution in config['distributions']:
                    weights=distribution_weights([cases[i]['context'] for i in indices],distribution)
                    report=summarize(times[indices],energies[indices] if energies is not None else None,weights)
                    for j,ratio in enumerate(ratios):
                        worst=cases[indices[report['worst_case'][j]]]
                        metrics.append(dict(alpha=alpha,beta=beta,utilization=utilization['id'],portfolio=portfolio,
                            distribution=distribution,ratio=ratio,
                            **{k:None if v is None else bool(v[j]) if v.dtype==bool else float(v[j])
                               for k,v in report.items() if k!='worst_case'},
                            pareto_scope='latency_energy' if energies is not None else 'latency_only',
                            worst_scenario=worst['scenario'],worst_context=worst['context']))
    routing=[]
    c=v41.DEFAULT_CONFIG
    for batch in [1,8]:
        for context in config['contexts']:
            for segment,tokens in [('encoder_prefill',context),('decoder_replay',min(context,c.window_size))]:
                routing.append(dict(context=context,batch=batch,segment=segment,tokens_in_group=batch*tokens,
                    expert_assignments=batch*tokens*c.n_activated_experts,
                    mean_tokens_per_expert=batch*tokens*c.n_activated_experts/c.n_routed_experts))
    OUTPUT.mkdir(parents=True,exist_ok=True)
    datasets={'cases':cases,'evaluations':evaluations,'metrics':metrics,'deployments':deployments,'routing_scale':routing,
              'scenarios':config['scenarios']}
    for name,rows in datasets.items():write_csv(OUTPUT/f'{name}.csv',rows)
    report_files=render(config,cases,evaluations,metrics,ratios)
    def fingerprint(path):return dict(path=str(path.relative_to(ROOT)),sha256=hashlib.sha256(path.read_bytes()).hexdigest())
    inputs=[CONFIG,Path(__file__),ROOT/'scripts/v41_portfolio.py',ROOT/'scripts/deepseek_v41.py',ROOT/'scripts/hardware_cost.py',
            v41.SOURCE_DIR/'inference/config.json',ROOT/'data/DP_area_power/dp11_area_power_fixed_20261116.csv',
            ROOT/'data/DP_area_power/dp11_area_power_fixed_20261116.sources.json']
    manifest=dict(status='analytical_uncalibrated',config=config,source_metadata=metadata,
        assumptions=['One physical design across contexts; independent comparison for each budget',
            'Only five major operator families migrate; background work retains original precision',
            'Native FP4 index work stays included and varies with context',
            'Utilization coefficients are declared sensitivity assumptions, not measured batch-to-efficiency predictions',
            'Same per-mode routed utilization across candidates; no design-specific scheduling claim',
            'Nonideal utilization energy is null; no idle or switching-power scaling is assumed',
            'Routing scale is an average over experts for tokens in one group; does not predict padding, imbalance or saturation',
            'No new model-quality inference, EDA, scheduling, communication or memory-bandwidth simulation'],
        validation=dict(cases=len(cases),evaluations=len(evaluations),metrics=len(metrics),conserved_work=True),
        inputs=list(map(fingerprint,inputs)),outputs=[fingerprint(OUTPUT/f'{n}.csv') for n in datasets]+list(map(fingerprint,report_files)))
    (OUTPUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(manifest['validation'],indent=2))


if __name__=='__main__':main()
