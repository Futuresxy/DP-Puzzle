"""Nine-candidate joint-budget deployments and HQE region/workload analysis."""
import csv
import hashlib
import json
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.patches import Patch
import numpy as np

from hardware_cost import DATA, MODES, deploy, load_profiles, full_precision_profiles
from costs import mapped_work
from simplex import workload_grid, winner_regions, xy, HEIGHT

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / 'data/inputs/joint_dse.json'
EVIDENCE = ROOT / 'data/evidence/joint_dse_20261116'
COLORS = ['#d6e4f0', '#f8e5b9', '#c6dfca', '#decce8', '#f1c5b6',
          '#d6d2bf', '#a9d6cf', '#c3c7e6', '#edd6df']


def write_csv(path, rows):
    with path.open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]), lineterminator='\n')
        writer.writeheader()
        writer.writerows(rows)


def coefficients(rows):
    if any(not r['feasible'] for r in rows):
        raise ValueError('This region study requires at least one installed SM per candidate')
    capacity = np.array([[r[m + '_peak_tflops'] for m in MODES] for r in rows])
    power = np.array([[r[m + '_dp_power_w'] for m in MODES] for r in rows])
    return capacity, power, {'time': 1 / capacity, 'energy': power / capacity}


def winners(values, ratios):
    return '|'.join(r for r, v in zip(ratios, values)
                    if np.isclose(v, min(values), rtol=1e-10, atol=1e-14))


def draw_regions(regions, ratios, betas, output):
    plt.rcParams.update({'font.family': 'serif',
                         'font.serif': ['Times New Roman', 'Liberation Serif', 'STIXGeneral'],
                         'font.size': 9, 'mathtext.fontset': 'stix', 'pdf.fonttype': 42})
    fig, axes = plt.subplots(1, 4, figsize=(7.16, 2.30))
    panels = [('time', beta) for beta in betas] + [('energy', betas[0])]
    for panel, (ax, (objective, beta)) in enumerate(zip(axes, panels)):
        for region in regions[beta][objective]:
            if region['fraction'] < 1e-9:
                continue
            vertices = xy(region['vertices_hqe'])
            ax.fill(*vertices.T, color=COLORS[region['index']], ec='#5a5a5a', lw=.5)
            if region['fraction'] >= .025:
                center = vertices.mean(axis=0)
                if center[1] < .055:
                    ax.annotate(str(region['index'] + 1), xy=center,
                                xytext=(center[0], -.065), ha='center', va='center',
                                fontsize=8, weight='bold',
                                arrowprops={'arrowstyle': '-', 'lw': .5, 'color': '#333333'})
                else:
                    ax.text(*center, str(region['index'] + 1), ha='center', va='center',
                            fontsize=8, weight='bold')
        border = xy([[1, 0, 0], [0, 1, 0], [0, 0, 1], [1, 0, 0]])
        ax.plot(*border.T, color='#333333', lw=.7)
        ax.text(.5, HEIGHT+.04, 'H', ha='center', fontsize=9)
        ax.text(-.02, -.065, 'Q', ha='center', fontsize=9)
        ax.text(1.02, -.065, 'E', ha='center', fontsize=9)
        label = rf'({chr(97+panel)}) $\beta={beta}$' if objective == 'time' else '(d)'
        ax.text(.5, -.17, label, ha='center', fontsize=9)
        ax.set(xlim=(-.08, 1.08), ylim=(-.20, 1.0), aspect='equal')
        ax.axis('off')
    handles = [Patch(facecolor=color, edgecolor='#555555', label=f'{i+1}: {ratio}')
               for i, (color, ratio) in enumerate(zip(COLORS, ratios))]
    fig.legend(handles=handles, loc='lower center', ncol=5, fontsize=8,
               frameon=False, handlelength=1, columnspacing=1.1)
    fig.subplots_adjust(left=.015, right=.99, top=.99, bottom=.28, wspace=.15)
    fig.savefig(output, bbox_inches='tight', pad_inches=.03,
                metadata={'CreationDate': None, 'ModDate': None})
    plt.close(fig)


def make_table(all_rows, config, path):
    scenarios = {beta: [r for r in all_rows if r['alpha'] == float(config['figure_alpha'])
                       and r['beta'] == float(beta)] for beta in config['betas']}
    selected = scenarios[config['table_beta']]
    lines = [r'% Generated by scripts/reproduce_joint_dse.py.',
             r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrcr@{}}\toprule',
             r'Ratio & $A_C$ & $N_A$ & $N_{1.0}$ & $N_{1.5}$ & $N_{2.1}$ & $C_H/C_Q/C_E$ ($\beta=1.5$) & $\beta_{\rm full}$ \\\midrule']
    for i, row in enumerate(selected):
        peaks = '/'.join(f'{row[m+"_peak_tflops"]:.1f}' for m in MODES)
        counts = [str(scenarios[b][i]['installed_sms']) for b in config['betas']]
        lines.append(f"${row['ratio']}$ & {row['sm_area_mm2']:.3f} & {row['area_limited_sms']} & "
                     + ' & '.join(counts) + f" & {peaks} & {row['beta_for_area_full_deployment']:.3f}" + r' \\')
    lines.append(r'\bottomrule\end{tabular*}')
    path.write_text('\n'.join(lines) + '\n')


def main():
    config = json.loads(CONFIG.read_text())
    profiles, metadata = load_profiles()
    profiles = full_precision_profiles(profiles)
    ratios = [p['ratio'] for p in profiles]
    grid = workload_grid(config['simplex_divisions'])
    EVIDENCE.mkdir(parents=True, exist_ok=True)
    runs = ROOT / 'data/results/joint_dse_20261116'
    runs.mkdir(parents=True, exist_ok=True)
    points, ledgers = [], []
    for profile in config['workload_profiles']:
        for model in config['models']:
            for context in config['contexts']:
                work, excluded, ledger = mapped_work(model, 'prefill', context, profile, config['batch'])
                hqe = np.array([work[0], work[1], work[2] + work[3]])
                total = hqe.sum()
                points.append(dict(profile=profile, model=model, context=context,
                                   h_flops=hqe[0], q_flops=hqe[1], e_flops=hqe[2],
                                   x_H=hqe[0]/total, x_Q=hqe[1]/total, x_E=hqe[2]/total,
                                   hqe_coverage=total/(total+excluded), excluded_fp32_flops=excluded))
                ledgers.append(dict(profile=profile, model=model, context=context, operators=ledger))
    all_rows, summaries, evaluations, selections, scan_rows = [], [], [], [], []
    regions, figure_regions = {}, {}
    reference_energy = None
    for alpha in config['alphas']:
        for beta in config['betas']:
            rows = deploy(profiles, alpha, beta, config['baseline_sms'], config['dp_per_sm'])
            all_rows.extend(rows)
            capacity, power, coeff = coefficients(rows)
            if reference_energy is None:
                reference_energy = coeff['energy']
            np.testing.assert_allclose(coeff['energy'], reference_energy, rtol=1e-12)
            scenario = f'alpha={alpha},beta={beta}'
            regions[scenario] = {}
            for objective, costs in coeff.items():
                polygons = winner_regions(costs)
                assert abs(sum(p['fraction'] for p in polygons) - 1) < 1e-7
                regions[scenario][objective] = polygons
                for region in polygons:
                    summaries.append(dict(alpha=alpha, beta=beta, objective=objective,
                                          ratio=ratios[region['index']], fraction=region['fraction']))
                    if region['fraction'] > 1e-9:
                        vertex_costs = np.array(region['vertices_hqe']) @ costs.T
                        assert np.all(vertex_costs[:, region['index']] <= vertex_costs.min(axis=1) + 1e-9)
                for x, values in zip(grid, grid @ costs.T):
                    scan_rows.append(dict(alpha=alpha, beta=beta, objective=objective,
                                          x_H=x[0], x_Q=x[1], x_E=x[2], winner=winners(values, ratios)))
            if alpha == config['figure_alpha']:
                figure_regions[beta] = regions[scenario]
            for point in points:
                flops = np.array([point['h_flops'], point['q_flops'], point['e_flops']])
                times = coeff['time'] @ flops / 1e12
                energies = coeff['energy'] @ flops / 1e12
                selections.append(dict(alpha=alpha, beta=beta, **point,
                                       fastest=winners(times, ratios), least_energy=winners(energies, ratios)))
                for i, ratio in enumerate(ratios):
                    evaluations.append(dict(alpha=alpha, beta=beta, profile=point['profile'], model=point['model'],
                        context=point['context'], ratio=ratio, seconds=times[i], dp_energy_j=energies[i],
                        average_dp_power_w=energies[i]/times[i], max_dp_power_w=max(power[i]),
                        speedup_over_baseline=times[0]/times[i], energy_over_baseline=energies[i]/energies[0]))
    for name, rows in [('deployments', all_rows), ('region_shares', summaries),
                       ('workload_points', points), ('workload_evaluations', evaluations), ('selections', selections)]:
        write_csv(EVIDENCE / (name + '.csv'), rows)
    write_csv(runs / 'simplex_sweep.csv', scan_rows)
    (runs / 'workload_ledger.json').write_text(json.dumps(ledgers, indent=2) + '\n')
    (EVIDENCE / 'regions.json').write_text(json.dumps({'ratios': ratios, 'scenarios': regions}, indent=2) + '\n')
    figure = ROOT / 'figures/joint_dse_regions.pdf'
    draw_regions(figure_regions, ratios, config['betas'], figure)
    table = ROOT / 'tables/hardware_joint_table.tex'
    make_table(all_rows, config, table)
    sources = [CONFIG, DATA, ROOT / 'data/DP_area_power' / metadata['csv']]
    sources += [ROOT / 'scripts' / s for s in ['hardware_cost.py', 'reproduce_joint_dse.py',
                'simplex.py', 'costs.py', 'workloads.py', 'deepseek_v41.py']]
    sources += [ROOT / 'data/inputs/models' / m / 'inference/config.json' for m in config['models']]
    outputs = list(EVIDENCE.glob('*.csv')) + [EVIDENCE / 'regions.json', figure, table,
                                            runs / 'simplex_sweep.csv', runs / 'workload_ledger.json']
    def fingerprint(path):
        return dict(path=str(path.relative_to(ROOT)), sha256=hashlib.sha256(path.read_bytes()).hexdigest())
    manifest = dict(status='analytical_uncalibrated', config=config, ratios=ratios,
                    command='python3 scripts/reproduce_joint_dse.py',
                    validation={'designs': 9, 'scenarios': 9, 'points_per_simplex': len(grid),
                                'simplex_rows': len(scan_rows), 'workload_points': len(points),
                                'evaluations': len(evaluations), 'region_partition_pass': True,
                                'region_vertices_optimal_pass': True, 'energy_budget_invariance_pass': True},
                    power_scope='DP pool; Qwen activity proxy, MXFP4 proxy for NVFP4 expert scenario',
                    source_metadata=metadata, inputs=list(map(fingerprint, sources)), outputs=list(map(fingerprint, outputs)))
    (EVIDENCE / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps(manifest['validation'], indent=2))


if __name__ == '__main__':
    main()
